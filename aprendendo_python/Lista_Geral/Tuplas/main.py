# Aprendendo Tuplas em Python
# Tuplas são semelhantes às listas, mas são imutáveis. Isso significa que, uma vez que uma tupla é criada, seus elementos não podem ser alterados, adicionados ou removidos. Tuplas são definidas usando parênteses (). 

# 1 - exemplo de tupla

coordenadas = (10.0, 20.0)
print("Coordenadas: \nX: ", coordenadas[0], "\nY: ", coordenadas[1])  # Saída: (10.0, 20.0

# 2 - exemplo de tupla com diferentes tipos de dados

dias_semana = ("Segunda", "Terça", "Quarta", "Quinta", "Sexta")
print("Dias da semana e números: ", dias_semana)  # Saída: ('Segunda', 'Terça', 'Quarta', 'Quinta', 'Sexta')

